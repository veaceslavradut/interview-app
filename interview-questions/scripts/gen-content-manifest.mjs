// Generates src/data/content-manifest.js — the LIGHT content layer.
//
// Item 9 (code splitting): only three consumers ever read a question's `answer`
// (QuestionPage, ReviewSessionPage, the search index). Everything else needs no
// more than category meta + question TEXT. So we ship a small, answer-free
// manifest in the entry bundle and lazy-load the heavy answer markdown per
// category (see src/data/localized.js).
//
// This runs in Node (predev / prebuild), reading the RU/EN barrels — the same
// source of truth the tests use — and stripping every `answer` field. The output
// is committed so a plain `vite build` works without running codegen first; the
// pre-hooks just keep it from drifting (a stale manifest shows up as a git diff).

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { categories } from '../src/data/questions.js';
import { enContent } from '../src/data/content.en.js';

const meta = categories.map((c) => ({
  id: c.id,
  title: c.title,
  icon: c.icon,
  description: c.description,
  // optional markdown blurb shown as a section intro on the category page
  ...(c.intro != null ? { intro: c.intro } : {}),
  // subtopic groups the category page's question list under section headings
  questions: c.questions.map((q) => ({
    id: q.id,
    question: q.question,
    ...(q.subtopic ? { subtopic: q.subtopic } : {}),
  })),
}));

const enMeta = {};
for (const [catId, override] of Object.entries(enContent)) {
  const entry = {};
  if (override.title != null) entry.title = override.title;
  if (override.description != null) entry.description = override.description;
  if (override.intro != null) entry.intro = override.intro;
  if (override.questions) {
    const questions = {};
    for (const [qId, q] of Object.entries(override.questions)) {
      // keep only the translated TEXT; the EN answer is lazy-loaded like the RU one
      if (q.question != null) questions[qId] = { question: q.question };
    }
    entry.questions = questions;
  }
  enMeta[catId] = entry;
}

const out = `// AUTO-GENERATED by scripts/gen-content-manifest.mjs — do not edit by hand.
// Light content manifest: category meta + question text, WITHOUT answers.
// Answers are lazy-loaded per category (see localized.js: loadAnswer/loadAllFull).
export const categoriesMeta = ${JSON.stringify(meta)};

export const enContentMeta = ${JSON.stringify(enMeta)};
`;

const outPath = fileURLToPath(new URL('../src/data/content-manifest.js', import.meta.url));
writeFileSync(outPath, out);
console.log(
  `content-manifest.js: ${meta.length} categories, ` +
    `${meta.reduce((n, c) => n + c.questions.length, 0)} questions (answers stripped)`
);
