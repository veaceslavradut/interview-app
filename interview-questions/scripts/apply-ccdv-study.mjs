// Regenerates the CCD "study card" data files from three committed inputs:
//   src/data/ccdvStudy.en.json      — English master (question/options/correct/why/subtopic)
//   src/data/ccdvStudy.why-ru.json  — RU translations of each `why` (fill in batches)
//   src/data/quiz/ccdvImported.ru.json — already-translated RU question + options
//
// Each single-answer imported quiz question becomes a studiable Q&A whose answer
// is the option list (correct one marked) + the explanation. RU question/options
// are reused from the quiz translation; only `why` needs translating here.
//
// A card is emitted only once its `why` is translated (RU) — so the set grows as
// ccdvStudy.why-ru.json fills. Duplicate question texts are dropped deterministically
// (keep first), which keeps the data-integrity test's "no duplicate question text"
// invariant. Outputs (do not edit by hand):
//   src/data/ccdvStudy-questions.js     — RU source array (spread into the category)
//   src/data/ccdvStudy-questions-en.js  — EN override object keyed by id
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const master = JSON.parse(readFileSync(here('../src/data/ccdvStudy.en.json'), 'utf8'));
const whyRu = JSON.parse(readFileSync(here('../src/data/ccdvStudy.why-ru.json'), 'utf8'));
const quizRu = JSON.parse(readFileSync(here('../src/data/quiz/ccdvImported.ru.json'), 'utf8'));

const norm = (s) => String(s).replace(/\s+/g, ' ').trim().toLowerCase();
const letter = (i) => String.fromCharCode(65 + i);

// Concept duplicates: each is a reworded twin of an earlier card with an
// identical correct answer + explanation. Drop the later id of each pair → 145.
const EXCLUDE = new Set(['ccd-study-64', 'ccd-study-65', 'ccd-study-67']);

function buildAnswer(question, options, correct, why) {
  const list = options
    .map((o, i) => (i === correct ? `- ✅ **${letter(i)}.** ${o}` : `- **${letter(i)}.** ${o}`))
    .join('\n');
  return `${question}\n\n${list}\n\n**Правильно:** ${letter(correct)}\n\n${why}`;
}

// Deterministic dedup by question text (English master order), independent of
// translation progress, so the included id set is stable.
const seen = new Set();
const included = new Set();
for (const m of master) {
  if (EXCLUDE.has(m.id)) continue;
  const key = norm(m.question);
  if (seen.has(key)) continue;
  seen.add(key);
  included.add(m.id);
}

const ru = [];
const en = {};
let emitted = 0;
for (const m of master) {
  if (!included.has(m.id)) continue;
  const why = whyRu[m.id];
  if (!why) continue; // not yet translated
  const q = quizRu[m.quizId];
  if (!q) throw new Error(`missing RU quiz translation for ${m.quizId}`);
  ru.push({
    id: m.id,
    question: q.question,
    answer: buildAnswer(q.question, q.options, m.correct, why),
    subtopic: m.subtopic,
  });
  en[m.id] = {
    question: m.question,
    answer: buildAnswer(m.question, m.options, m.correct, m.why),
  };
  emitted++;
}

const header = (extra) =>
  `// AUTO-GENERATED by scripts/apply-ccdv-study.mjs — do not edit by hand.\n// ${extra}\n`;

writeFileSync(
  here('../src/data/ccdvStudy-questions.js'),
  header('Russian study cards derived from the imported single-answer quiz questions.') +
    `export const ccdvStudyQuestions = ${JSON.stringify(ru, null, 2)};\n`
);
writeFileSync(
  here('../src/data/ccdvStudy-questions-en.js'),
  header('English overrides for the CCD study cards (keyed by question id).') +
    `export const ccdvStudyQuestionsEn = ${JSON.stringify(en, null, 2)};\n`
);

console.log(
  `study cards: ${emitted} emitted / ${included.size} included (of ${master.length} single-answer; ` +
    `${master.length - included.size} dropped as duplicate text)`
);
